import { Hono } from "hono";
import { deleteCookie, setCookie } from "hono/cookie";
import { sign } from "hono/jwt";
import type { User } from "../../../shared/src/lib/utils/validation";
import { userSockets, announcedUsers } from "../state";
import { createUser, deleteUser, getUserByUsername, getUser, getUserWithAuth } from "../db";

const app = new Hono();

app.post("/register", async (c) => {
    const body = await c.req.json();
    const { username, password, user } = body;

    if (!username || !password || !user) {
        return c.json({ error: "Missing required fields" }, 400);
    }

    const existing = getUserByUsername(username);
    if (existing) {
        return c.json({ error: "Username taken" }, 409);
    }

    const passhash = await Bun.password.hash(password);

    // Ensure the user object has the username and uid (if valid)
    // We should probably trust the UID generated by frontend or generate one here.
    // For now, assume frontend sends a valid User object.

    const success = createUser(
        { ...user, username }, // ensure username matches
        passhash,
        false // not a guest
    );

    if (!success) {
        return c.json({ error: "Failed to create user" }, 500);
    }

    // Auto-login after register
    const payload = { user: { ...user, username } };
    const secret = process.env.JWT_SECRET || "fallback_secret_for_dev";
    const token = await sign(payload, secret);

    setCookie(c, "sessionid", token, {
        maxAge: 60 * 60 * 24 * 7,
        httpOnly: false,
        secure: false, // Set true in production
        path: "/",
        sameSite: "lax",
    });

    return c.json({
        uid: user.uid,
        username: username,
        token: token,
    });
});

app.post("/login", async (c) => {
    const body = await c.req.json();
    const { username, password } = body;

    if (!username || !password) {
        return c.json({ error: "Missing credentials" }, 400);
    }

    const record = getUserWithAuth(username);
    if (!record) {
        return c.json({ error: "Invalid credentials" }, 401);
    }

    const { user, passhash } = record;

    if (!passhash) {
        return c.json({ error: "Account requires setup or is guest" }, 401);
    }

    const match = await Bun.password.verify(password, passhash);
    if (!match) {
        return c.json({ error: "Invalid credentials" }, 401);
    }

    const payload = { user };
    const secret = process.env.JWT_SECRET || "fallback_secret_for_dev";
    const token = await sign(payload, secret);

    setCookie(c, "sessionid", token, {
        maxAge: 60 * 60 * 24 * 7,
        httpOnly: false,
        secure: false,
        path: "/",
        sameSite: "lax",
    });

    return c.json({
        uid: user.uid,
        username: user.username,
        token: token,
    });
});

