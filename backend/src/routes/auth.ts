app.post("/logout", (c) => {
    const user: User = c.get("jwtPayload")?.user;

    if (user) {
        const uid = user.uid;
        announcedUsers.delete(uid);
        const userSocket = userSockets.get(uid);
        if (userSocket) {
            userSocket.close();
        }
        userSockets.delete(uid);
    }

    deleteCookie(c, "sessionid", {
        maxAge: 0,
        httpOnly: false,
        path: "/",
        secure: false,
        sameSite: "lax",
    });

    return c.json({ message: "logged out" });
});

export default app;
